from src.domain.incident_correlation import CommitRef, IncidentCorrelator  # noqa: E402

SUMMARY_PATH = REPO_ROOT / "attribution_holdout_summary.json"
MEASURED_BY_COMMAND = "python scripts/attribution_split.py"

#: HELD-OUT uses a seed that no earlier run of this repository used. TRAIN keeps the
#: published default (``attribution_train.TRAIN_SEED``).
HELD_OUT_SEED = 20260927

#: Ceilings of the generator's propagation delay (minutes from a commit landing to the
#: error rate moving) that the sensitivity block re-scores at. The published corpus uses
#: ``trial.PROPAGATION_DELAY_MINUTES``, whose ceiling is 75 minutes, and the shipped window
#: is also 75 minutes. Both sides of the split share that authored ceiling, so the
#: held-out side cannot reveal a fit to it; this table is how a reader sees what it is worth.
DELAY_CEILINGS_MINUTES = (60, 75, 90, 120, 180)

#: Other held-out seeds, to show how much of the published figure is the one seed's draw.
#: First run by the 2026-09-27 audit of this split; no parameter was tuned on any of them.
SPREAD_SEEDS = tuple(range(20261001, 20261021))


# -------------------------------------------------- The held-out side of the split


def held_out_corpus(
    commits: list[CommitRef], seed: int = HELD_OUT_SEED,
    propagation_delay_minutes: tuple[float, float] = trial.PROPAGATION_DELAY_MINUTES,
) -> tuple[list, list[CommitRef]]:
    """The corpus the published figure comes from. Never used to choose a parameter."""
    _, held_out = split_stream(commits)
    return trial.build_corpus(held_out, seed=seed,
                              propagation_delay_minutes=propagation_delay_minutes), held_out


# ----------------------------------------------------------------- The engines


def engine_v1() -> IncidentCorrelator:
    """The engine as shipped until 2026-09-27: 60 minute window, names only a lone change."""
    return IncidentCorrelator(attribution_window_minutes=60, max_commits_in_window=1)


def engine_v2() -> IncidentCorrelator:
    """Chosen on the train split by ``python scripts/tune_attribution.py``, then frozen.

    75 minute window ending at the onset, names a change only when exactly one landed in
    it, no service scope. Frozen before its first held-out run.
    """
    return IncidentCorrelator(attribution_window_minutes=75, max_commits_in_window=1)


#: Every engine scored here, oldest first. The last one is the shipped default.
ENGINES: dict[str, dict] = {
    "v1_2026_09_08": {
        "build": engine_v1,
        "description": (
            "Pre-onset baseline, 3.0x threshold, 60 minute window ending at the onset, "
            "names a change only when exactly one commit landed in the window."
        ),
    },
    "v2_2026_09_27": {
        "build": engine_v2,
        "description": (
            "As v1, with the attribution window widened to 75 minutes. Chosen on the train "
            "split by python scripts/tune_attribution.py and frozen before its held-out run."
        ),
    },
}
SHIPPED_ENGINE = "v2_2026_09_27"


# ------------------------------------------------------------------- Scoring


def wilson_interval(successes: int, trials: int, z: float = 1.96) -> list[float] | None:
    """95% Wilson score interval, because the held-out namings are few."""
    if trials == 0:
        return None
    p = successes / trials
    denominator = 1 + z * z / trials
    centre = (p + z * z / (2 * trials)) / denominator
    half = z * math.sqrt(p * (1 - p) / trials + z * z / (4 * trials * trials)) / denominator
    return [round(max(0.0, centre - half), 4), round(min(1.0, centre + half), 4)]


def figures(cases: list, commits: list[CommitRef], correlator: IncidentCorrelator) -> dict:
    """The five figures published for each side, with the counts behind each."""
    verdicts = trial.run_corpus(cases, commits, correlator)
    summary = trial.aggregate(cases, verdicts)
    head = summary["headline"]
    regressions = [v for v in verdicts if v.truth == trial.TRUTH_REGRESSION]
    exogenous = [v for v in verdicts if v.stratum == trial.STRATUM_EXOGENOUS]
    healthy = [v for v in verdicts if v.stratum == trial.STRATUM_HEALTHY]
    hits = sum(1 for v in regressions if v.outcome == trial.HIT)
    named = sum(1 for v in verdicts if v.outcome in trial.NAMED_A_COMMIT)
    refused = sum(1 for v in verdicts if v.outcome in trial.REFUSED_TO_NAME)
    false_exo = sum(1 for v in exogenous if v.outcome == trial.FALSE_ATTRIBUTION)
    quiet = sum(1 for v in healthy if v.outcome == trial.CORRECT_QUIET)
    return {
        "cases": len(verdicts),
        "naming_precision": head["naming_precision"],
        "naming_precision_95ci": wilson_interval(hits, named),
        "times_a_commit_was_named": named,
        "correct_namings": hits,
        "naming_recall_on_regressions": head["naming_recall_on_regressions"],
        "naming_recall_95ci": wilson_interval(hits, len(regressions)),
        "regressions": len(regressions),
        "refused_to_name_rate_on_all_anomalies": head["refused_to_name_rate_on_all_anomalies"],
        "anomalies_seen": refused + named,
        "refused_no_candidate": summary["why_it_named_nobody"]["no_candidate_in_window"],
        "refused_window_too_crowded": summary["why_it_named_nobody"]["window_too_crowded"],
        "false_attribution_rate_on_exogenous_spikes": head["false_attribution_rate_on_exogenous_spikes"],
        "false_attributions_on_exogenous_spikes": false_exo,
        "quiet_rate_on_healthy_series": head["quiet_rate_on_healthy_series"],
        "quiet_on_healthy_series": quiet,
        "healthy_series": len(healthy),
        "exogenous_spikes": len(exogenous),
        "wrong_namings": named - hits,
        "exogenous_refused_no_candidate": sum(1 for v in exogenous if v.outcome == trial.CORRECT_REFUSAL),
        "exogenous_refused_crowded": sum(1 for v in exogenous if v.outcome == trial.CORRECT_REFUSAL_CROWDED),
        "regressions_refused_no_candidate": sum(
            1 for v in regressions if v.outcome == trial.REFUSED_ON_REGRESSION),
        "regressions_refused_crowded": sum(
            1 for v in regressions if v.outcome == trial.REFUSED_CROWDED_ON_REGRESSION),
        "regressions_named_wrong_commit": sum(1 for v in regressions if v.outcome == trial.WRONG_COMMIT),
        "regressions_never_called_an_anomaly": sum(
            1 for v in regressions if v.outcome == trial.MISSED_REGRESSION),
        "unexpected_outcomes": summary["unexpected_outcomes"],
    }


def delay_ceiling_sensitivity(commits: list[CommitRef]) -> dict:
    """Re-score both engines on held-out corpora whose only change is the delay ceiling.

    Nothing is chosen from this table and no engine changes: v2 stays frozen at the 75
    minute window chosen on train. Each corpus uses the held-out seed, so the random
    draws line up case by case and the one thing that moves is how far a regression's
    onset may trail its cause. The floor of the delay stays at the published value.
    """
    floor = trial.PROPAGATION_DELAY_MINUTES[0]
    rows = []
    for ceiling in DELAY_CEILINGS_MINUTES:
        cases, held_out = held_out_corpus(commits, propagation_delay_minutes=(floor, float(ceiling)))
        for name, spec in ENGINES.items():
            f = figures(cases, held_out, spec["build"]())
            rows.append({
                "delay_ceiling_minutes": ceiling,
                "engine": name,
                "naming_precision": f["naming_precision"],
                "naming_precision_95ci": f["naming_precision_95ci"],
                "times_a_commit_was_named": f["times_a_commit_was_named"],
                "correct_namings": f["correct_namings"],
                "naming_recall_on_regressions": f["naming_recall_on_regressions"],
                "regressions_named_wrong_commit": f["regressions_named_wrong_commit"],
                "false_attributions_on_exogenous_spikes": f["false_attributions_on_exogenous_spikes"],
            })
    return {
        "side": "held_out",
        "seed": HELD_OUT_SEED,
        "published_delay_minutes": list(trial.PROPAGATION_DELAY_MINUTES),
        "note": (
            "The generator draws each regression's delay uniformly between the floor and a "
            "ceiling the authors chose, 75 minutes, and the shipped window was widened to "
            "exactly 75 minutes on the train split, which shares that ceiling. So the "
            "held-out precision is conditional on the assumption that a regression shows "
            "within 75 minutes. These rows move only the ceiling. Nothing was chosen from "
            "them."
        ),
        "rows": rows,
    }


def held_out_seed_spread(commits: list[CommitRef]) -> dict:
    """Both frozen engines on held-out corpora built from other seeds, same commits.

    The Wilson interval on the headline covers the namings of one seed only. This block
    shows the generator-seed variance it leaves out. Nothing is chosen from it.
    """
    per_engine: dict[str, list[dict]] = {name: [] for name in ENGINES}
    for seed in SPREAD_SEEDS:
        cases, held_out = held_out_corpus(commits, seed=seed)
        for name, spec in ENGINES.items():
            f = figures(cases, held_out, spec["build"]())
            per_engine[name].append({
                "seed": seed,
                "naming_precision": f["naming_precision"],
                "times_a_commit_was_named": f["times_a_commit_was_named"],
                "correct_namings": f["correct_namings"],
                "false_attributions_on_exogenous_spikes": f["false_attributions_on_exogenous_spikes"],
            })
    engines = {}
    for name, rows in per_engine.items():
        precisions = [r["naming_precision"] for r in rows if r["naming_precision"] is not None]
        engines[name] = {
            "mean_naming_precision": round(statistics.mean(precisions), 4),
            "sd_naming_precision": round(statistics.stdev(precisions), 4),
            "min_naming_precision": min(precisions),
            "max_naming_precision": max(precisions),
            "mean_correct_namings": round(statistics.mean(r["correct_namings"] for r in rows), 2),
            "mean_false_attributions_on_exogenous_spikes": round(
                statistics.mean(r["false_attributions_on_exogenous_spikes"] for r in rows), 2),
            "rows": rows,
        }
    names = list(ENGINES)
    wins = sum(
        1 for a, b in zip(per_engine[names[0]], per_engine[names[-1]])
        if (b["naming_precision"] or 0) > (a["naming_precision"] or 0)
    )
    return {
        "seeds": [SPREAD_SEEDS[0], SPREAD_SEEDS[-1]],
        "note": (
            "Held-out commits, other seeds, the published delay ceiling. Not tuned on. "
            "Shows the seed-to-seed variance the single-seed Wilson interval leaves out."
        ),
        "shipped_more_precise_than_previous_on_seeds": wins,
        "engines": engines,
    }


def build_summary() -> dict:
    commits, recording = trial.load_commit_stream()
    train_cases, train = train_corpus(commits)
    held_cases, held_out = held_out_corpus(commits)
    engines = []
    for name, spec in ENGINES.items():
        engines.append({
            "engine": name,
            "description": spec["description"],
            "train": figures(train_cases, train, spec["build"]()),
            "held_out": figures(held_cases, held_out, spec["build"]()),
        })
    return {
        "measured_by_command": MEASURED_BY_COMMAND,
        "measured_at_utc": datetime.now(timezone.utc).isoformat(),
        "measured_on": platform.platform(),
        "python_version": platform.python_version(),
        "label": SYNTHETIC_LABEL,
        "split": {
            "rule": (
                "Chronological cut of the recorded commit stream. TRAIN is every commit before "
                "the cut, HELD-OUT every commit at or after it. Each side builds its own corpus "
                "with the unchanged generator in scripts/correlation_trial.py: regression causes "
                "from that side's commits, uncaused reading times over that side's span, its own "
                "fixed seed. Parameters are tuned on TRAIN only."
            ),
            "cut_utc": SPLIT_CUT_UTC.isoformat(),
            "idle_gap_at_cut_minutes": idle_gap_at_cut_minutes(commits),
            "max_window_considered_minutes": MAX_WINDOW_CONSIDERED_MINUTES,
            "train_commits": len(train),
            "held_out_commits": len(held_out),
            "train_span_utc": [train[0].committed_at.isoformat(), train[-1].committed_at.isoformat()],
            "held_out_span_utc": [held_out[0].committed_at.isoformat(), held_out[-1].committed_at.isoformat()],
            "train_commits_per_hour": trial.commit_density_per_hour(train),
            "held_out_commits_per_hour": trial.commit_density_per_hour(held_out),
            "train_burstiness": trial.burstiness(train),
            "held_out_burstiness": trial.burstiness(held_out),
            "train_seed": TRAIN_SEED,
            "held_out_seed": HELD_OUT_SEED,
            "commit_stream_recorded_at_head": recording.get("recorded_at_head"),
            "propagation_delay_minutes": list(trial.PROPAGATION_DELAY_MINUTES),
        },
        "shipped_engine": SHIPPED_ENGINE,
        "engines": engines,
        "delay_ceiling_sensitivity": delay_ceiling_sensitivity(commits),
        "held_out_seed_spread": held_out_seed_spread(commits),
    }


def print_report(summary: dict) -> None:
    split = summary["split"]
    print(f"Attribution engine, train/held-out split (seeds {split['train_seed']} / "
          f"{split['held_out_seed']}). {summary['label']}")
    print(f"  split: {split['train_commits']} train commits before {split['cut_utc']}, "
          f"{split['held_out_commits']} held-out commits after it, idle gap at the cut "
          f"{split['idle_gap_at_cut_minutes']} minutes")
    for row in summary["engines"]:
        marker = " (shipped)" if row["engine"] == summary["shipped_engine"] else ""
        print(f"  engine {row['engine']}{marker}: {row['description']}")
        for side in ("train", "held_out"):
            f = row[side]
            print(f"    {side:<8} precision {f['naming_precision']} ({f['correct_namings']}/"
                  f"{f['times_a_commit_was_named']}, 95% CI {f['naming_precision_95ci']})  "
                  f"recall {f['naming_recall_on_regressions']} ({f['correct_namings']}/{f['regressions']})  "
                  f"refused {f['refused_to_name_rate_on_all_anomalies']} of {f['anomalies_seen']} anomalies "
                  f"({f['refused_no_candidate']} empty, {f['refused_window_too_crowded']} crowded)  "
                  f"false attribution on exogenous {f['false_attribution_rate_on_exogenous_spikes']}  "
                  f"quiet on healthy {f['quiet_rate_on_healthy_series']}")
    sensitivity = summary["delay_ceiling_sensitivity"]
    print(f"  held-out precision by the generator's delay ceiling (published "
          f"{sensitivity['published_delay_minutes']}; nothing chosen from these rows):")
    for r in sensitivity["rows"]:
        print(f"    ceiling {r['delay_ceiling_minutes']:>3} min  {r['engine']}  precision "
              f"{r['naming_precision']} ({r['correct_namings']}/{r['times_a_commit_was_named']}, "
              f"95% CI {r['naming_precision_95ci']})  recall {r['naming_recall_on_regressions']}  "
              f"wrong commit on a regression {r['regressions_named_wrong_commit']}")
    spread = summary["held_out_seed_spread"]
    print(f"  held-out precision over seeds {spread['seeds'][0]} to {spread['seeds'][1]} "
          f"(shipped engine more precise on {spread['shipped_more_precise_than_previous_on_seeds']} "
          f"of {len(SPREAD_SEEDS)}):")
    for name, e in spread["engines"].items():
        print(f"    {name}  mean {e['mean_naming_precision']} (sd {e['sd_naming_precision']}, "
              f"range {e['min_naming_precision']} to {e['max_naming_precision']})  "
              f"mean correct namings {e['mean_correct_namings']}  mean false attributions on "
              f"exogenous {e['mean_false_attributions_on_exogenous_spikes']}")


#: Fields that describe the run rather than the result. They differ between a Windows
#: workstation and a Linux CI runner, so ``--check`` compares everything else.
RUN_METADATA_KEYS = ("measured_at_utc", "measured_on", "python_version")


def drifted_keys(recorded: dict, fresh: dict, prefix: str = "") -> list[str]:
    """Every dotted path where the recorded summary and a fresh run disagree."""
    drifted = []
    for key in sorted(set(recorded) | set(fresh)):
        if not prefix and key in RUN_METADATA_KEYS:
            continue
        path = f"{prefix}{key}"
        old, new = recorded.get(key), fresh.get(key)
        if isinstance(old, dict) and isinstance(new, dict):
            drifted += drifted_keys(old, new, path + ".")
        elif old != new:
            drifted.append(path)
    return drifted


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="re-score and compare against the recorded summary without writing it")
    parser.add_argument("--no-write", action="store_true")
    args = parser.parse_args()
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

    summary = build_summary()
    if args.check:
        if not SUMMARY_PATH.exists():
            print(f"{SUMMARY_PATH.name} does not exist; run {MEASURED_BY_COMMAND} first")
            return 1
        recorded = json.loads(SUMMARY_PATH.read_text(encoding="utf-8"))
        drifted = drifted_keys(recorded, summary)
        if drifted:
            print("the recorded held-out summary no longer matches a fresh run: " + ", ".join(drifted))
            return 1
        print(f"{SUMMARY_PATH.name} matches a fresh run in every field but the run metadata "
              f"({len(summary['engines'])} engine(s), {len(summary['delay_ceiling_sensitivity']['rows'])} "
              f"delay-ceiling rows, {len(SPREAD_SEEDS)} spread seeds)")
        return 0

    if not args.no_write:
        SUMMARY_PATH.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    print_report(summary)
    unexpected = sum(row[side]["unexpected_outcomes"] for row in summary["engines"]
                     for side in ("train", "held_out"))
    return 1 if unexpected else 0


if __name__ == "__main__":
    raise SystemExit(main())
